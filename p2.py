# Data types used in AI
name = "AI Bot"          # str
age = 2                # int
accuracy = 98.6        # float
is_active = True       # bool
sensors = ["camera", "lidar", "mic"]  # list
config = {"model": "GPT", "version": 4} # dict

print(type(name), name)
print(type(age), age)
print(type(accuracy), accuracy)
print(type(is_active), is_active)
print(type(sensors), sensors)
print(type(config), config)
